// Small shared helpers: seeded RNG, statistics, binary heap.

export function mulberry32(seed) {
  let a = seed >>> 0
  return function () {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

export const clamp = (v, lo, hi) => Math.min(hi, Math.max(lo, v))
export const lerp = (a, b, t) => a + (b - a) * t
export const uniform = (rng, lo, hi) => lo + (hi - lo) * rng()

export function quantile(sorted, q) {
  if (!sorted.length) return NaN
  const pos = (sorted.length - 1) * q
  const lo = Math.floor(pos)
  const hi = Math.ceil(pos)
  return sorted[lo] + (sorted[hi] - sorted[lo]) * (pos - lo)
}

export const sortedCopy = (arr) => Float64Array.from(arr).sort()

export function ranks(arr) {
  const idx = Array.from(arr, (v, i) => [v, i]).sort((a, b) => a[0] - b[0])
  const r = new Float64Array(arr.length)
  idx.forEach(([, i], k) => {
    r[i] = k
  })
  return r
}

export function pearson(a, b) {
  const n = a.length
  let ma = 0
  let mb = 0
  for (let i = 0; i < n; i++) {
    ma += a[i]
    mb += b[i]
  }
  ma /= n
  mb /= n
  let sab = 0
  let saa = 0
  let sbb = 0
  for (let i = 0; i < n; i++) {
    const da = a[i] - ma
    const db = b[i] - mb
    sab += da * db
    saa += da * da
    sbb += db * db
  }
  return saa && sbb ? sab / Math.sqrt(saa * sbb) : 0
}

export const spearman = (a, b) => pearson(ranks(a), ranks(b))

// Min-heap keyed by a numeric priority.
export class MinHeap {
  constructor() {
    this.k = []
    this.v = []
  }
  get size() {
    return this.k.length
  }
  push(key, val) {
    const { k, v } = this
    let i = k.length
    k.push(key)
    v.push(val)
    while (i > 0) {
      const p = (i - 1) >> 1
      if (k[p] <= key) break
      k[i] = k[p]
      v[i] = v[p]
      i = p
    }
    k[i] = key
    v[i] = val
  }
  peekKey() {
    return this.k.length ? this.k[0] : Infinity
  }
  pop() {
    const { k, v } = this
    const topV = v[0]
    const lastK = k.pop()
    const lastV = v.pop()
    const n = k.length
    if (n > 0) {
      let i = 0
      for (;;) {
        let c = 2 * i + 1
        if (c >= n) break
        if (c + 1 < n && k[c + 1] < k[c]) c++
        if (k[c] >= lastK) break
        k[i] = k[c]
        v[i] = v[c]
        i = c
      }
      k[i] = lastK
      v[i] = lastV
    }
    return topV
  }
}
