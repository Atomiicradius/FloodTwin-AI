"""Download and verify every raw source in `data/MANIFEST.yaml`.

Usage:
    python -m floodtwin.geo.fetch            # download missing files, verify hashes
    python -m floodtwin.geo.fetch --verify   # verify only (no network)

On first download the SHA-256, byte size and UTC access date are written to
`data/MANIFEST.lock.yaml` (kept separate so the hand-written manifest stays readable).
Later runs refuse to proceed if a hash changes (the upstream file was modified): that is a
data-version event and must be logged in the Decision Log, not silently accepted.
"""

from __future__ import annotations

import argparse
import datetime as dt
import logging
import sys
import time
from pathlib import Path

import requests
import yaml

from floodtwin.geo.config import REPO_ROOT, manifest, sha256_file

log = logging.getLogger(__name__)
LOCK = REPO_ROOT / "data" / "MANIFEST.lock.yaml"
USER_AGENT = "floodtwin-research-data-fetch/0.1"


class HashMismatchError(RuntimeError):
    """Raised when a downloaded file no longer matches the locked hash."""


def _load_lock() -> dict:
    if LOCK.exists():
        return yaml.safe_load(LOCK.read_text(encoding="utf-8")) or {}
    return {}


def _download(url: str, dest: Path, timeout_s: int = 600, attempts: int = 4) -> None:
    dest.parent.mkdir(parents=True, exist_ok=True)
    tmp = dest.with_suffix(dest.suffix + ".part")
    for k in range(attempts):
        try:
            with requests.get(url, stream=True, timeout=timeout_s, headers={"User-Agent": USER_AGENT}) as r:
                r.raise_for_status()
                expected = r.headers.get("Content-Length")
                with open(tmp, "wb") as fh:
                    for block in r.iter_content(1 << 20):
                        fh.write(block)
            if expected is not None and tmp.stat().st_size != int(expected):
                raise OSError(f"short read: {tmp.stat().st_size} of {expected} bytes")
            tmp.replace(dest)
            return
        except (requests.RequestException, OSError) as exc:
            log.warning("download attempt %d/%d failed for %s: %s", k + 1, attempts, url, exc)
            time.sleep(10 * (k + 1))
    raise RuntimeError(f"could not download {url} after {attempts} attempts")


def fetch_all(verify_only: bool = False) -> dict:
    """Download missing sources and verify hashes. Returns the updated lock dict."""
    lock = _load_lock()
    for src in manifest()["sources"]:
        sid = src["id"]
        dest = REPO_ROOT / "data" / "raw" / sid / src["filename"]
        if not dest.exists():
            if verify_only:
                raise FileNotFoundError(f"{sid}: {dest} missing (run without --verify)")
            log.info("downloading %s", sid)
            _download(src["url"], dest)
            lock.setdefault(sid, {})["accessed_utc"] = dt.datetime.now(dt.timezone.utc).isoformat(
                timespec="seconds"
            )
        digest = sha256_file(dest)
        entry = lock.setdefault(sid, {})
        if "sha256" in entry and entry["sha256"] != digest:
            raise HashMismatchError(
                f"{sid}: sha256 {digest} != locked {entry['sha256']}. Upstream changed; "
                "log a data-version decision before updating the lock."
            )
        entry.update(sha256=digest, bytes=dest.stat().st_size, url=src["url"])
        log.info("ok %s %s", sid, digest[:12])
    LOCK.write_text(
        "# Generated by floodtwin.geo.fetch — do not edit by hand.\n"
        + yaml.safe_dump(lock, sort_keys=True),
        encoding="utf-8",
    )
    return lock


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--verify", action="store_true", help="verify only, no downloads")
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")
    fetch_all(verify_only=args.verify)
    return 0


if __name__ == "__main__":
    sys.exit(main())
